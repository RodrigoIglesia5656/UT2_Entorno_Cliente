let dia = 2;

switch (dia) {
    case 1:
        console.log("Lunes"); // Al no coincidir lo valores, no entra e el case
        break;
    case 2:
        console.log("Martes"); // Este es el que se ejecutará
        break;
    case 3:
        console.log("Miércoles");
        break;
    default:
        console.log("Día no válido");
}

